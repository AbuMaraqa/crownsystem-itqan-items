<?php

namespace Modules\Items\Support\Search;

/**
 * طريقة مطابقة كلمات البحث لمستند الصنف، من الادق الى الاوسع.
 */
enum MatchMode
{
    /**
     * كل كلمة بداية كلمة في المستند، بأي ترتيب.
     */
    case Words;

    /**
     * كل كلمة في اي موضع من المستند، ولو وسط كلمة.
     */
    case Contains;

    /**
     * اي كلمة من كلمات البحث، ويتقدم ما طابق منها اكثر.
     */
    case AnyWord;
}
